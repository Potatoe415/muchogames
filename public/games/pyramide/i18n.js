  function detectInitialLocale(supportedLocales) {
    const browserLocale = String(globalThis.navigator?.language ?? "fr").slice(0, 2).toLowerCase();
    return supportedLocales.includes(browserLocale) ? browserLocale : "fr";
  }

  function translate(locale, key, params = {}) {
    const entry = MESSAGES[locale]?.[key] ?? MESSAGES.fr[key] ?? key;
    if (typeof entry === "function") {
      return entry(params);
    }

    return String(entry).replace(/\{(\w+)\}/g, (_, token) => String(params[token] ?? ""));
  }

