export function translate(lang, key, vars = {}) {
  const text = (COPY[lang] || COPY.fr)[key] ?? COPY.fr[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}
