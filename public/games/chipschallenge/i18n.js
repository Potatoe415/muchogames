// French typography: no line break before ! ? : ;
const frenchSpaces = (text) => text.replace(/ ([!?:;])/g, "\u00a0$1");

export function translate(lang, key, vars = {}) {
  const text = STRINGS[lang]?.[key] ?? STRINGS.fr[key] ?? key;
  const filled = text.replace(/\{(\w+)\}/g, (_, name) =>
    String(vars[name] ?? "")
  );
  return lang === "fr" ? frenchSpaces(filled) : filled;
}

export const rulesHtml = (lang) => RULES[lang] || RULES.fr;
